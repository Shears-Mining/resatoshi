"""CLI regression tests: python3 contrib/devtools/test_headerssync_params.py."""
from pathlib import Path
import subprocess
import sys
import unittest


class HeadersSyncParamsTest(unittest.TestCase):
    SCRIPT = Path(__file__).with_name('headerssync-params.py')

    def run_model(self, *args, expected=0):
        result = subprocess.run([sys.executable, str(self.SCRIPT), *args],
                                capture_output=True, text=True, timeout=30)
        self.assertEqual(result.returncode, expected, result.stdout + result.stderr)
        self.assertNotIn('Traceback', result.stderr)
        return result

    def test_equivalent_timezones(self):
        outputs = [self.run_model('--genesis', date, '--minchainwork-headers', '8001',
                                  '--evaluate', '1', '1').stdout
                   for date in ('2026-09-04', '2026-09-04T00:00:00Z', '2026-09-04T09:00:00+09:00')]
        outputs = ["\n".join(line for line in output.splitlines() if "// Generated by" not in line) for output in outputs]
        self.assertEqual(outputs[0], outputs[1])
        self.assertEqual(outputs[0], outputs[2])
        self.assertIn('Expected forged headers per attack: 0.25;', outputs[0])

    def test_invalid_profiles(self):
        for args in (('--genesis', 'not-a-date'),
                     ('--genesis', '0001-01-01T00:00:00+01:00'),
                     ('--genesis', '2029-01-01'),
                     ('--minchainwork-headers', '0'),
                     ('--attack-cost-headers', '0'),
                     ('--attack-cost-headers', '938344'),
                     ('--evaluate', '0', '1'),
                     ('--evaluate', '1', '-1'),
                     ('--genesis', '2026-09-04', '--horizon', '2026-09-04T00:00:01',
                      '--minchainwork-headers', '8001')):
            with self.subTest(args=args):
                self.assertIn('error:', self.run_model(*args, expected=2).stderr)

    def test_underflow_is_not_zero_risk(self):
        for buffer in ('2000', str(10**20)):
            with self.subTest(buffer=buffer):
                result = self.run_model('--evaluate', '1', buffer, expected=2)
                self.assertIn('does not mean zero risk', result.stderr)
                self.assertNotIn('within budget:', result.stdout)

    def test_header_count_model_bound(self):
        for cost in ((), ('--attack-cost-headers', '1')):
            with self.subTest(cost=cost):
                result = self.run_model('--minchainwork-headers', str(10**400),
                                        '--evaluate', '1', '1', *cost, expected=2)
                self.assertIn('exceeds the model horizon header bound', result.stderr)
                self.assertEqual(result.stdout, '')
        common = ('--genesis', '2026-09-04', '--horizon', '2026-09-04T00:00:01')
        self.run_model(*common, '--minchainwork-headers', '6', '--evaluate', '1', '1')
        self.run_model(*common, '--minchainwork-headers', '7', '--evaluate', '1', '1', expected=2)
        self.run_model(*common, '--minchainwork-headers', '6', expected=2)

    def test_reciprocal_overflow(self):
        # Cover both sides of the binary64 reciprocal boundary, and a much
        # smaller positive subnormal rate. No success output on range errors.
        finite = self.run_model('--evaluate', '1', '1022')
        self.assertNotIn('inf attacks', finite.stdout)
        self.assertIn('- Attack rate:', finite.stdout)
        for buffer in ('1023', '1073'):
            with self.subTest(buffer=buffer):
                result = self.run_model('--evaluate', '1', buffer, expected=2)
                self.assertIn('does not mean infinite attack cost', result.stderr)
                self.assertEqual(result.stdout, '')

    def test_small_period(self):
        result = self.run_model('--evaluate', '1', '2')
        self.assertIn('Expected forged headers per attack: 0.125;', result.stdout)

    def test_small_positive_optimization_domain(self):
        result = self.run_model('--genesis', '2026-09-04', '--horizon', '2026-09-04T00:00:01',
                                '--minchainwork-headers', '1')
        self.assertIn('.commitment_period = 1,', result.stdout)
        self.assertIn('within budget: True', result.stdout)

    def test_existing_profile_and_separate_attack_cost(self):
        common = ('--genesis', '2026-09-04', '--minchainwork-headers', '8001', '--evaluate', '191', '6000')
        baseline = self.run_model(*common).stdout
        conservative = self.run_model(*common, '--attack-cost-headers', '2000').stdout
        for output in (baseline, conservative):
            self.assertIn('Expected forged headers per attack: 3.73925343042e-08;', output)
            self.assertIn('mainchain sync: 281.255 KiB', output)
            self.assertIn('timewarp attack: 254.119 KiB', output)
            self.assertIn('within budget: True', output)
        self.assertIn('limit: 2.88036e-07;', baseline)
        self.assertIn('limit: 7.2e-08;', conservative)
        inherited = self.run_model('--genesis', '2026-09-04', '--minchainwork-headers', '8001',
                                   '--evaluate', '641', '15218').stdout
        self.assertIn('Expected forged headers per attack: 3.37698744498e-05;', inherited)


if __name__ == '__main__':
    unittest.main()
